import streamlit as st
import pandas as pd
import numpy as np
import plotly.express as px

# ---------------------------------------------------------------------
# إعدادات الصفحة (لازم تكون أول أمر من أوامر streamlit)
# ---------------------------------------------------------------------
st.set_page_config(page_title='لوحة مبيعات المتجر', layout='wide')

# أمر صغير لجعل النص يبدأ من اليمين لأن اللغة عربية
st.markdown(
    """
    <style>
    .stApp { direction: rtl; text-align: right; }
    </style>
    """,
    unsafe_allow_html=True
)


# =====================================================================
# الخطوة 1: توليد بيانات المتجر (نفس الكود المعطى في المهمة)
# =====================================================================
# st.cache_data تجعل البيانات تتولد مرة واحدة فقط، فلا تتغير ولا تبطؤ اللوحة
@st.cache_data
def توليد_البيانات():
    np.random.seed(10)                 # الرقم الثابت يجعل النتائج نفسها كل مرة
    عدد_الطلبات = 500
    التواريخ = pd.date_range('2023-01-01', '2024-12-31', freq='D')

    المنتجات = ['Laptop', 'Mouse', 'Keyboard', 'Monitor', 'Headphones', 'Webcam', 'Speaker', 'Tablet']
    الفئات = {'Laptop': 'Electronics', 'Mouse': 'Accessories', 'Keyboard': 'Accessories',
              'Monitor': 'Electronics', 'Headphones': 'Accessories', 'Webcam': 'Accessories',
              'Speaker': 'Electronics', 'Tablet': 'Electronics'}
    الأسعار = {'Laptop': 500, 'Mouse': 15, 'Keyboard': 25, 'Monitor': 150,
               'Headphones': 40, 'Webcam': 35, 'Speaker': 60, 'Tablet': 300}
    المدن = ['عمان', 'إربد', 'الزرقاء', 'العقبة']

    الطلبات = pd.DataFrame({
        'order_date': np.random.choice(التواريخ, عدد_الطلبات),
        'product': np.random.choice(المنتجات, عدد_الطلبات),
        'quantity': np.random.randint(1, 5, عدد_الطلبات),
        'city': np.random.choice(المدن, عدد_الطلبات, p=[0.5, 0.2, 0.2, 0.1]),
        'customer_id': np.random.randint(1, 101, عدد_الطلبات)
    })
    الطلبات['category'] = الطلبات['product'].map(الفئات)
    الطلبات['unit_price'] = الطلبات['product'].map(الأسعار)
    الطلبات['revenue'] = الطلبات['quantity'] * الطلبات['unit_price']
    الطلبات = الطلبات.sort_values('order_date').reset_index(drop=True)
    return الطلبات


البيانات = توليد_البيانات()

# أسماء الأشهر بالعربي لنستخدمها في العناوين
أسماء_الأشهر = {1: 'كانون الثاني', 2: 'شباط', 3: 'آذار', 4: 'نيسان', 5: 'أيار', 6: 'حزيران',
                7: 'تموز', 8: 'آب', 9: 'أيلول', 10: 'تشرين الأول', 11: 'تشرين الثاني', 12: 'كانون الأول'}


# =====================================================================
# الخطوة 2: تصميم المؤشرات الأربعة (KPIs) ومبرراتها
# =====================================================================
# 1) إجمالي الإيراد: Actionable لأنه يقارن أداء أي فترة أو مدينة أو فئة
#    فنعرف أين نزيد الإنفاق التسويقي وأين نعالج الضعف (ليس رقماً للزينة).
# 2) عدد الطلبات: Actionable لأنه يفصل بين "نحتاج زبائن أكثر" و"نحتاج سلة أكبر"،
#    وإذا نزل نراجع الحملات والإعلانات.
# 3) متوسط قيمة الطلب: Actionable لأنه يوجّه قرارات العروض (حزم، شحن مجاني فوق مبلغ)
#    لرفع قيمة السلة بدون جلب زبائن جدد.
# 4) عدد العملاء الفريدين: Actionable لأنه يقيس اتساع قاعدة الزبائن الحقيقية، وإذا
#    كان قريباً من عدد الطلبات فالمشكلة في الولاء فنبني برنامج ولاء (وليس مجرد عدد زيارات).


# =====================================================================
# الخطوة 3: الشريط الجانبي (الفلاتر)
# =====================================================================
st.sidebar.header('الفلاتر')

أقل_تاريخ = البيانات['order_date'].min().date()
أعلى_تاريخ = البيانات['order_date'].max().date()

# فلتر 1: نطاق التاريخ
نطاق_التاريخ = st.sidebar.date_input(
    'نطاق التاريخ',
    value=(أقل_تاريخ, أعلى_تاريخ),
    min_value=أقل_تاريخ,
    max_value=أعلى_تاريخ
)

# أحياناً يختار المستخدم تاريخ البداية فقط، فننتظر حتى يختار تاريخ النهاية
if len(نطاق_التاريخ) != 2:
    st.info('اختر تاريخ البداية وتاريخ النهاية من الشريط الجانبي.')
    st.stop()

تاريخ_البداية, تاريخ_النهاية = نطاق_التاريخ

# فلتر 2: الفئة (مع خيار الكل)
قائمة_الفئات = ['الكل'] + sorted(البيانات['category'].unique())
الفئة_المختارة = st.sidebar.selectbox('الفئة', قائمة_الفئات)

# فلتر 3: المدينة (مع خيار الكل)
قائمة_المدن = ['الكل'] + sorted(البيانات['city'].unique())
المدينة_المختارة = st.sidebar.selectbox('المدينة', قائمة_المدن)

# ---------------------------------------------------------------------
# تطبيق الفلاتر على البيانات خطوة خطوة
# ---------------------------------------------------------------------
البيانات_المفلترة = البيانات[
    (البيانات['order_date'].dt.date >= تاريخ_البداية) &
    (البيانات['order_date'].dt.date <= تاريخ_النهاية)
]

if الفئة_المختارة != 'الكل':
    البيانات_المفلترة = البيانات_المفلترة[البيانات_المفلترة['category'] == الفئة_المختارة]

if المدينة_المختارة != 'الكل':
    البيانات_المفلترة = البيانات_المفلترة[البيانات_المفلترة['city'] == المدينة_المختارة]

# إذا لم يبقَ أي صف بعد الفلترة نتوقف برسالة بدل أن يحدث خطأ
if len(البيانات_المفلترة) == 0:
    st.warning('لا توجد طلبات تطابق هذه الفلاتر. غيّر الاختيارات من الشريط الجانبي.')
    st.stop()


# =====================================================================
# الخطوة 4: العنوان الرئيسي (يوصل رسالة وليس مجرد وصف)
# =====================================================================
نسبة_عمان_الكلية = البيانات.loc[البيانات['city'] == 'عمان', 'revenue'].sum() / البيانات['revenue'].sum() * 100
نسبة_الإلكترونيات_الكلية = البيانات.loc[البيانات['category'] == 'Electronics', 'revenue'].sum() / البيانات['revenue'].sum() * 100

st.title('الإلكترونيات تصنع أغلب إيراد المتجر وعمّان أكبر سوق: أين نركز النمو؟')
st.caption(
    f'الأرقام الكلية للفترة كاملة: الإلكترونيات {نسبة_الإلكترونيات_الكلية:.0f}% من الإيراد، '
    f'وعمّان {نسبة_عمان_الكلية:.0f}% منه. استخدم الفلاتر لتفحص أي جزء بالتفصيل.'
)


# =====================================================================
# صف المؤشرات (KPIs) - تتحدث تلقائياً مع الفلاتر
# =====================================================================
إجمالي_الإيراد = البيانات_المفلترة['revenue'].sum()
عدد_الطلبات = len(البيانات_المفلترة)
متوسط_قيمة_الطلب = إجمالي_الإيراد / عدد_الطلبات
عدد_العملاء = البيانات_المفلترة['customer_id'].nunique()

عمود1, عمود2, عمود3, عمود4 = st.columns(4)
عمود1.metric('إجمالي الإيراد', f'{إجمالي_الإيراد:,.0f} دينار')
عمود2.metric('عدد الطلبات', f'{عدد_الطلبات:,}')
عمود3.metric('متوسط قيمة الطلب', f'{متوسط_قيمة_الطلب:,.2f} دينار')
عمود4.metric('عدد العملاء الفريدين', f'{عدد_العملاء:,}')

st.divider()


# =====================================================================
# رسمة الاتجاه الزمني: الإيراد الشهري (Resampling)
# =====================================================================
# نجعل التاريخ هو الفهرس ثم نجمع الإيراد لكل شهر (MS = بداية كل شهر)
الإيراد_الشهري = البيانات_المفلترة.set_index('order_date')['revenue'].resample('MS').sum()
جدول_الشهري = الإيراد_الشهري.reset_index()
جدول_الشهري.columns = ['الشهر', 'الإيراد']

# نجد أعلى شهر لنضعه في عنوان الرسمة (عنوان فيه رسالة)
أعلى_شهر = الإيراد_الشهري.idxmax()
قيمة_أعلى_شهر = الإيراد_الشهري.max()
عنوان_الاتجاه = (
    f'ذروة الإيراد كانت في {أسماء_الأشهر[أعلى_شهر.month]} {أعلى_شهر.year} '
    f'بقيمة {قيمة_أعلى_شهر:,.0f} دينار'
)

رسمة_الاتجاه = px.line(جدول_الشهري, x='الشهر', y='الإيراد', markers=True, title=عنوان_الاتجاه)
st.plotly_chart(رسمة_الاتجاه, use_container_width=True)


# =====================================================================
# رسمة مقارنة الفئات + جدول المنتجات والعملاء
# =====================================================================
الإيراد_حسب_الفئة = البيانات_المفلترة.groupby('category')['revenue'].sum().reset_index()
الإيراد_حسب_الفئة.columns = ['الفئة', 'الإيراد']

# عنوان فيه رسالة: الفئة الأولى ونسبتها
الفئة_الأولى = الإيراد_حسب_الفئة.sort_values('الإيراد', ascending=False).iloc[0]
نسبة_الفئة_الأولى = الفئة_الأولى['الإيراد'] / إجمالي_الإيراد * 100
عنوان_الفئات = f'فئة {الفئة_الأولى["الفئة"]} تحقق {نسبة_الفئة_الأولى:.0f}% من الإيراد'

رسمة_الفئات = px.bar(الإيراد_حسب_الفئة, x='الفئة', y='الإيراد', title=عنوان_الفئات, text_auto=',.0f')
st.plotly_chart(رسمة_الفئات, use_container_width=True)

# أفضل 5 منتجات حسب الإيراد
أفضل_منتجات = (
    البيانات_المفلترة.groupby('product')['revenue'].sum()
    .sort_values(ascending=False).head(5).reset_index()
)
أفضل_منتجات.columns = ['المنتج', 'الإيراد']

# أفضل 5 عملاء حسب إجمالي الإنفاق
أفضل_عملاء = (
    البيانات_المفلترة.groupby('customer_id')['revenue'].sum()
    .sort_values(ascending=False).head(5).reset_index()
)
أفضل_عملاء.columns = ['رقم العميل', 'إجمالي الإنفاق']

عمود_أ, عمود_ب = st.columns(2)
with عمود_أ:
    st.subheader('أفضل 5 منتجات حسب الإيراد')
    st.dataframe(أفضل_منتجات, use_container_width=True, hide_index=True)
with عمود_ب:
    st.subheader('أفضل 5 عملاء حسب إجمالي الإنفاق')
    st.dataframe(أفضل_عملاء, use_container_width=True, hide_index=True)

st.divider()


# =====================================================================
# الخطوة 4: قصة البيانات - أهم الملاحظات (تُحسب من البيانات المفلترة)
# =====================================================================
st.header('أهم الملاحظات')

# ملاحظة 1: المدن
الإيراد_حسب_المدينة = البيانات_المفلترة.groupby('city')['revenue'].sum().sort_values(ascending=False)
if len(الإيراد_حسب_المدينة) > 1:
    المدينة_الأولى = الإيراد_حسب_المدينة.index[0]
    نسبة_المدينة_الأولى = الإيراد_حسب_المدينة.iloc[0] / إجمالي_الإيراد * 100
    المدينة_الأخيرة = الإيراد_حسب_المدينة.index[-1]
    نسبة_المدينة_الأخيرة = الإيراد_حسب_المدينة.iloc[-1] / إجمالي_الإيراد * 100
    st.markdown(
        f'**1) تركّز جغرافي:** مدينة {المدينة_الأولى} تمثل {نسبة_المدينة_الأولى:.0f}% من الإيراد، '
        f'بينما {المدينة_الأخيرة} تمثل {نسبة_المدينة_الأخيرة:.0f}% فقط. '
        f'فرصة: حملة تسويقية موجهة للمدن الأضعف لتقليل الاعتماد على مدينة واحدة.'
    )
else:
    st.markdown(
        f'**1) تركّز جغرافي:** الفلتر الحالي يعرض مدينة {المدينة_المختارة} فقط. '
        f'اختر "الكل" في فلتر المدينة لمقارنة المدن ببعضها.'
    )

# ملاحظة 2: المنتجات الأعلى إيراداً
إيراد_المنتجات = البيانات_المفلترة.groupby('product')['revenue'].sum().sort_values(ascending=False)
if len(إيراد_المنتجات) > 1:
    المنتج_الأول = إيراد_المنتجات.index[0]
    المنتج_الثاني = إيراد_المنتجات.index[1]
    نسبة_أول_منتجين = (إيراد_المنتجات.iloc[0] + إيراد_المنتجات.iloc[1]) / إجمالي_الإيراد * 100
    st.markdown(
        f'**2) اعتماد على منتجين:** {المنتج_الأول} و{المنتج_الثاني} يحققان معاً {نسبة_أول_منتجين:.0f}% من الإيراد. '
        f'خطر: أي نقص بمخزونهما أو منافسة على سعرهما يهز المتجر كله، فيجب ضمان توفرهما '
        f'وتنويع المنتجات ذات الهامش الجيد.'
    )
else:
    st.markdown(f'**2) اعتماد على منتج:** الفلتر الحالي فيه منتج واحد فقط هو {إيراد_المنتجات.index[0]}.')

# ملاحظة 3: كبار العملاء
إنفاق_العملاء = البيانات_المفلترة.groupby('customer_id')['revenue'].sum().sort_values(ascending=False)
نسبة_أفضل_5 = إنفاق_العملاء.head(5).sum() / إجمالي_الإيراد * 100
if نسبة_أفضل_5 < 30:
    st.markdown(
        f'**3) قاعدة عملاء موزعة:** أفضل 5 عملاء يمثلون {نسبة_أفضل_5:.0f}% فقط من الإيراد '
        f'(من أصل {عدد_العملاء} عميل). لا يوجد اعتماد خطير على عميل واحد، لكن يمكن إطلاق '
        f'برنامج ولاء لكبار العملاء لزيادة تكرار شرائهم.'
    )
else:
    st.markdown(
        f'**3) تركّز على كبار العملاء:** أفضل 5 عملاء يمثلون {نسبة_أفضل_5:.0f}% من الإيراد '
        f'(من أصل {عدد_العملاء} عميل). خسارة أحدهم تؤثر على الإيراد، فيجب الاهتمام بهم '
        f'ببرنامج ولاء وتواصل مباشر.'
    )
